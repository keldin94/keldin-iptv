ROOT=Path("app/src/main/java/com/keldin/iptv")
def edit(path,fn):
    p=ROOT/path; old=p.read_text(); new=fn(old)
    if old==new:raise AssertionError("v912 no changes: "+path)
    p.write_text(new)
def one(s,a,b,label):
    if a not in s:raise AssertionError("v912 missing "+label+": "+a[:105])
    return s.replace(a,b,1)

